import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
const source = readFileSync(new URL("../web/moss_layout_data.js", import.meta.url), "utf8");
const m = await import("data:text/javascript;base64," + Buffer.from(source).toString("base64"));
const draft = m.template("poster");
assert.deepEqual(m.presetSize(1048576, "1:1"), [1024, 1024]);
assert.deepEqual(m.presetSize(1572864, "3:2"), [1536, 1024]);
for (const [pixels] of m.PIXEL_PRESETS) for (const aspect of m.ASPECT_PRESETS) {
  const [w, h] = m.presetSize(pixels, aspect);
  assert.ok(w % 16 === 0 && h % 16 === 0 && w <= 4096 && h <= 4096);
}
assert.equal(m.mpLabel(1536, 1024), "1.57 MP");
assert.equal(m.sizePreset(1536, 1024).pixels, "1572864");
const upstream = { id: 1, type: "Resolution", outputs: [{name:"width"},{name:"height"}], widgets: [{name:"width",value:1536},{name:"height",value:1024}] };
const graph = { links: {7:{origin_id:1,origin_slot:0},8:{origin_id:1,origin_slot:1}}, getNodeById:id=>id===1?upstream:null };
const node = { inputs:[{name:"width",link:7},{name:"height",link:8}], graph, properties:{} };
assert.equal(m.resolutionInputs(node).width, 1536);
assert.equal(m.resolutionInputs(node).height, 1024);
upstream.widgets[0].value = 2048; assert.equal(m.resolutionInputs(node).width, 2048);
upstream.inputs = [{name:"width",link:9}];
assert.deepEqual(m.resolutionInputs(node).pending, ["width"], "Wired widgets cannot use stale local values");
node.properties.allbuyMossResolution = {key:m.resolutionInputs(node).key,width:768,height:1024};
assert.equal(m.resolutionInputs(node).width, 768);
assert.deepEqual(m.resolutionInputs(node).cached, ["width"]);
node.inputs[0].link = null;
assert.equal(m.resolutionInputs(node).width, undefined, "Disconnecting restores the draft's own width");
assert.equal(draft.items.length, 3);
assert.equal(draft.width % 16, 0);
assert.equal(draft.height % 16, 0);
assert.deepEqual(m.moveBox([10, 20, 110, 120], -100, 1000, 200, 200), [0, 100, 100, 200]);
assert.deepEqual(m.moveBox([10, 20, 110, 120], 5, 5, 200, 200, 16), [16, 32, 116, 132]);
assert.deepEqual(m.resizeBox([10, 20, 110, 120], "nw", 500, -500, 200, 200), [109, 0, 110, 120]);
assert.deepEqual(m.resizeBox([10, 20, 110, 120], "se", 500, -500, 200, 200), [10, 20, 200, 21]);
assert.deepEqual(m.editEdge([10, 20, 110, 120], 0, 150, 200, 200), [109, 20, 110, 120]);
assert.deepEqual(m.resizeLayout(draft, 512, 768, true).items[0].bbox, draft.items[0].bbox.map(n => n / 2));
assert.deepEqual(m.resizeLayout(draft, 512, 768, false).items[0].bbox, draft.items[0].bbox);
const history = new m.History(draft), changed = structuredClone(draft); changed.items[0].caption = "edited";
history.push(changed);
assert.equal(history.step(-1).items[0].caption, draft.items[0].caption);
assert.equal(history.step(1).items[0].caption, "edited");
history.step(-1); history.push(m.blankLayout());
assert.equal(history.step(1), null, "A new change clears the redo branch");
console.log("PASS: MOSS layout geometry, resizing, templates and history");
