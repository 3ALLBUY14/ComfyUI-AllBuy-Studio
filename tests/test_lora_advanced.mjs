import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import vm from "node:vm";

const source = readFileSync(new URL("../web/lora_stack_advanced.js", import.meta.url), "utf8");
const context = vm.createContext({});
vm.runInContext(source.slice(source.indexOf("const key"), source.indexOf("let previews;")).replaceAll("export ", "")
  + "\nglobalThis.rules={rowActive,resolveName,masterToggle,assignGroup,contiguousGroups,moveGroup,modelChain,normalizeMissingPolicy};", context);
const { resolveName, masterToggle, assignGroup, contiguousGroups, moveGroup, modelChain } = context.rules;
const plain = value => JSON.parse(JSON.stringify(value));
for (const value of [undefined, null, "", "None", false, "缺失时停止", "error"]) assert.equal(context.rules.normalizeMissingPolicy(value), "error");
assert.equal(context.rules.normalizeMissingPolicy("skip"), "skip");
assert.equal(resolveName("old/a.safetensors", ["new/a.safetensors"]).name, "new/a.safetensors");
assert.equal(resolveName("old/a.safetensors", ["b/a.safetensors", "c/a.safetensors"]).status, "ambiguous");
assert.equal(resolveName("A\\B.safetensors", ["a/b.safetensors"]).status, "moved");
assert.equal(resolveName("None", []).status, "empty");
const original = [{ id: "a", enabled: true, group: "style", group_off: true }, { id: "b", enabled: false }, { id: "c", enabled: true }];
const off = masterToggle(original, null);
assert.ok(off.entries.every(entry => !entry.enabled));
const restored = masterToggle(off.entries, off.saved);
assert.deepEqual(plain(restored.entries).map(({enabled,group_off})=>[enabled,!!group_off]), [[true,true],[false,false],[true,false]]);
const grouped = assignGroup(original, ["b", "c"], "style");
assert.deepEqual(plain(grouped).map(entry => entry.id), ["a", "b", "c"]);
assert.ok(grouped.every(entry => entry.group_off), "joining a disabled group preserves its disabled state");
const ungrouped = assignGroup(grouped, ["b"], "");
assert.deepEqual(plain(contiguousGroups([{id:1,group:"a"},{id:2},{id:3,group:"a"}])).map(e=>e.id), [1,3,2]);
assert.equal(ungrouped[1].group_off, false);
assert.deepEqual(plain(moveGroup([{id:1,group:"a"},{id:2,group:"a"},{id:3,group:"b"},{id:4}],"a",1)).map(e=>e.id), [3,1,2,4]);
const a = { id:1, outputs:[{type:"MODEL",links:[1]}] };
const loader = { id:2, type:"LoraLoaderModelOnly", mode:0, inputs:[{type:"MODEL",link:1}], outputs:[{type:"MODEL",links:[2]}], widgets:[{name:"lora_name",value:"repeat"},{name:"strength_model",value:.7}] };
const end = { id:3, type:"KSampler" };
const graph = { links:{1:{target_id:2,target_slot:0},2:{target_id:3,target_slot:0}},getNodeById:id=>({2:loader,3:end})[id] };
a.graph=graph;
assert.equal(modelChain(a).entries[0].weight,.7);
assert.equal(loader.mode,0,"planning never mutates source loaders");
loader.outputs[0].links.push(3);
assert.throws(()=>modelChain(a),/分叉/);
loader.outputs[0].links.pop();
loader.inputs.push({type:"STRING",link:9});
assert.throws(()=>modelChain(a),/其他连线/);
loader.inputs.pop();loader.type="LoraLoader";
assert.throws(()=>modelChain(a),/含 CLIP/);
console.log("PASS: file remapping, group state, master restoration, group movement and safe model-only chain planning");
